def get_lang() -> str:
    if _lang_cache["lang"] is None:
        try:
            _lang_cache["lang"] = _cfg.load_config().get("language", "pt")
        except Exception:
            return "pt"
    return _lang_cache["lang"]


def t(key: str, **kwargs) -> str:
    lang = get_lang()
    strings = _STRINGS.get(lang) or _STRINGS["pt"]
    val = strings.get(key) or _STRINGS["pt"].get(key, key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


def tl(key: str) -> list:
    lang = get_lang()
    strings = _STRINGS.get(lang) or _STRINGS["pt"]
    val = strings.get(key)
    if isinstance(val, list):
        return val
    fallback = _STRINGS["pt"].get(key)
    if isinstance(fallback, list):
        return fallback
    return []
